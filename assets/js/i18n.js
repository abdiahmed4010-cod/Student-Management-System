const listeners = [];

export const I18n = {
  getLanguage() {
    return localStorage.getItem(STORAGE_KEY) || 'en';
  },

  setLanguage(lang) {
    if (!['en', 'so', 'ar'].includes(lang)) lang = 'en';
    localStorage.setItem(STORAGE_KEY, lang);

    // Apply document direction and lang attributes
    const isRtl = lang === 'ar';
    document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', lang);

    // Notify registered listeners
    listeners.forEach(cb => {
      try {
        cb(lang, isRtl);
      } catch (e) {
        console.error('Error in i18n listener:', e);
      }
    });

    return lang;
  },

  isRTL() {
    return this.getLanguage() === 'ar';
  },

  onLanguageChange(callback) {
    if (typeof callback === 'function') {
      listeners.push(callback);
    }
  },

  t(path, fallback = '') {
    const lang = this.getLanguage();
    const catalog = TRANSLATIONS[lang] || TRANSLATIONS.en;

    const parts = path.split('.');
    let cur = catalog;
    for (const part of parts) {
      if (cur && cur[part] !== undefined) {
        cur = cur[part];
      } else {
        // Fallback to English catalog if missing
        let enCur = TRANSLATIONS.en;
        for (const p of parts) {
          if (enCur && enCur[p] !== undefined) {
            enCur = enCur[p];
          } else {
            return fallback || path;
          }
        }
        return enCur;
      }
    }
    return cur || fallback || path;
  },

  getAvailableLanguages() {
    return [
      { code: 'en', label: 'English', short: 'EN', dir: 'ltr' },
      { code: 'so', label: 'Af-Soomaali', short: 'SO', dir: 'ltr' },
      { code: 'ar', label: 'العربية', short: 'AR', dir: 'rtl' }
    ];
  }
};

